//! Generates the headers that upstream produces with CMake `configure_file`.

const std = @import("std");

pub const ResolvedLayer = struct {
    /// C++ class name / layer type string.
    name: []const u8,
    enabled: bool,
    /// Architecture directory (`x86`, `arm`, …) when an optimized
    /// implementation exists and is compiled in, e.g. `AbsVal_x86`.
    arch: ?[]const u8 = null,
};

const generated_notice =
    \\// Auto-generated by ncnn.zig build; do not edit.
    \\
;

pub fn layerDeclaration(allocator: std.mem.Allocator, layers: []const ResolvedLayer) ![]u8 {
    var aw: std.Io.Writer.Allocating = .init(allocator);
    errdefer aw.deinit();
    const w = &aw.writer;

    try w.writeAll(generated_notice);
    for (layers) |layer| {
        if (!layer.enabled) continue;
        const lower = try std.ascii.allocLowerString(allocator, layer.name);
        defer allocator.free(lower);

        try w.print("#include \"layer/{s}.h\"\n", .{lower});
        try w.print("namespace ncnn {{ DEFINE_LAYER_CREATOR({s}) }}\n", .{layer.name});

        if (layer.arch) |arch| {
            try w.print("#include \"layer/{s}/{s}_{s}.h\"\n", .{ arch, lower, arch });
            try w.print("namespace ncnn {{ DEFINE_LAYER_CREATOR({s}_{s}) }}\n", .{ layer.name, arch });
        }
    }

    return aw.toOwnedSlice();
}

pub fn layerTypeEnum(allocator: std.mem.Allocator, layers: []const ResolvedLayer) ![]u8 {
    var aw: std.Io.Writer.Allocating = .init(allocator);
    errdefer aw.deinit();
    const w = &aw.writer;

    try w.writeAll(generated_notice);
    for (layers, 0..) |layer, index| {
        try w.print("{s} = {d},\n", .{ layer.name, index });
    }

    return aw.toOwnedSlice();
}

pub fn layerRegistry(allocator: std.mem.Allocator, layers: []const ResolvedLayer) ![]u8 {
    var aw: std.Io.Writer.Allocating = .init(allocator);
    errdefer aw.deinit();
    const w = &aw.writer;

    try w.writeAll(generated_notice);

    try w.writeAll("static const layer_registry_entry layer_registry[] = {\n");
    try writeEntries(allocator, w, layers, .generic);
    try w.writeAll("};\n\nstatic const layer_registry_entry layer_registry_arch[] = {\n");
    try writeEntries(allocator, w, layers, .arch);
    try w.writeAll("};\n");

    const variants = [_]struct { macro: []const u8, name: []const u8 }{
        .{ .macro = "AVX512", .name = "avx512" },
        .{ .macro = "AVX", .name = "avx" },
        .{ .macro = "MSA", .name = "msa" },
        .{ .macro = "LASX", .name = "lasx" },
        .{ .macro = "LSX", .name = "lsx" },
        .{ .macro = "RVV", .name = "rvv" },
        .{ .macro = "XTHEADVECTOR", .name = "xtheadvector" },
    };
    for (variants) |variant| {
        try w.print(
            "\n#if NCNN_RUNTIME_CPU && NCNN_{s}\nstatic const layer_registry_entry layer_registry_{s}[] = {{\n",
            .{ variant.macro, variant.name },
        );
        try writeEntries(allocator, w, layers, .none);
        try w.print("}};\n#endif // NCNN_RUNTIME_CPU && NCNN_{s}\n", .{variant.macro});
    }

    try w.writeAll("\n#if NCNN_VULKAN\nstatic const layer_registry_entry layer_registry_vulkan[] = {\n");
    try writeEntries(allocator, w, layers, .none);
    try w.writeAll("};\n#endif // NCNN_VULKAN\n");

    return aw.toOwnedSlice();
}

const EntryMode = enum { generic, arch, none };

fn writeEntries(
    allocator: std.mem.Allocator,
    w: *std.Io.Writer,
    layers: []const ResolvedLayer,
    mode: EntryMode,
) !void {
    for (layers) |layer| {
        const creator: ?[]const u8 = switch (mode) {
            .generic => if (layer.enabled) layer.name else null,
            .arch => blk: {
                if (!layer.enabled) break :blk null;
                const arch = layer.arch orelse break :blk null;
                break :blk try std.fmt.allocPrint(allocator, "{s}_{s}", .{ layer.name, arch });
            },
            .none => null,
        };
        defer if (mode == .arch) {
            if (creator) |c| allocator.free(c);
        };

        try w.writeAll("#if NCNN_STRING\n");
        if (creator) |c|
            try w.print("{{\"{s}\", {s}_layer_creator}},\n", .{ layer.name, c })
        else
            try w.print("{{\"{s}\", 0}},\n", .{layer.name});
        try w.writeAll("#else\n");
        if (creator) |c|
            try w.print("{{{s}_layer_creator}},\n", .{c})
        else
            try w.writeAll("{0},\n");
        try w.writeAll("#endif\n");
    }
}

/// Placeholders for the shader headers; their initializers are only consumed
/// when Vulkan is enabled.
pub const empty_shader_registry: []const u8 = generated_notice;
pub const empty_shader_type_enum: []const u8 = generated_notice;
pub const empty_shader_spv_data: []const u8 = generated_notice;
